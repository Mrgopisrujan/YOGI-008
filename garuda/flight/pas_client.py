"""
Project AirSim (IAMAI fork) backend for GarudaOne.

Why this exists
---------------
The packaged UE 4.27 CityEnviron build exposes a crippled RPC surface: no
``takeoff``, no ``land``, no ``moveBy*`` family, and a ``simSpawnObject`` that
terminates the simulator process. Verified in isolation.

``projectairsim`` talks to the IAMAI fork over NNG (topics 8989, services 8990)
and has the full API this project needs.

Every call below was verified against the running environment. The traps, since
they cost real time and will cost it again:

* ``takeoff_async`` takes **no altitude**. Climb with
  ``move_by_velocity_async(v_down=-1.5)``.
* ``move_by_velocity_body_frame_async`` takes **``v_forward``/``v_right``/
  ``v_down``**, not ``v_north``/``v_east``.
* ``enable_api_control()`` takes no arguments; there is no ``set_autopilot``.
* Coroutines must be awaited twice: ``await (await drone.takeoff_async())``.
* ``get_ground_truth_pose()`` returns a plain dict, not an object with
  ``.position``.
* ``payload["data"]`` is raw ``bytes``. Use the library's ``unpack_image``;
  ``np.asarray`` on it yields a 0-d string. ``16FC1`` depth is float16 metres.
* ``unpack_image`` already returns **bottom-up** rows. Do not ``flipud`` again.
* Cameras are **pub/sub**, not polling. ``ImageDisplay.start()`` is required to
  pump the stock scene's steppable clock, or subscriptions are accepted and no
  frames ever publish.
* The stock scene names its robot ``Drone1``; the name must match the scene
  config exactly or the client raises ``Actor <name> not found in the config``.

It satisfies the same ``FlightBackend`` Protocol as ``AirSimClient``, so
``FollowController``, ``SubjectLock``, ``ObstacleAvoider`` and the shot planner
are unchanged.

Usage
-----
    from garuda.flight.pas_client import ProjectAirSimBackend

    b = ProjectAirSimBackend()
    b.connect()
    b.takeoff(altitude_m=4.0)
    frame = b.get_forward_camera()
    b.move_velocity_body(vx=1.0, vy=0.0, vz=0.0, yaw_rate_dps=20.0)
    b.hover()
    b.close()
"""

from __future__ import annotations

import asyncio
import atexit
import logging
import math
import threading
import time
from typing import Any, Optional, Sequence

import numpy as np

log = logging.getLogger("pas_client")

try:
    import projectairsim as pas
    from projectairsim.image_utils import ImageDisplay, unpack_image

    PAS_AVAILABLE = True
except ImportError:  # pragma: no cover - client is optional
    pas = None
    ImageDisplay = None
    unpack_image = None
    PAS_AVAILABLE = False

#: Scene config used by the follow loop. ``scene_follow.jsonc`` is generated by
#: ``scripts/make_follow_config.py`` and adds a nose-mounted ``FrontCamera``
#: carrying both scene and depth-perspective streams. The stock
#: ``scene_basic_drone.jsonc`` has no forward depth, which would leave the
#: obstacle avoider reading the pavement below instead of the flight path.
DEFAULT_SCENE = "scene_follow.jsonc"
DEFAULT_DRONE = "Drone1"

#: Follow sensors: nose scene + nose depth perspective.
FRONT_CAMERA = ("FrontCamera", "scene_camera")
FRONT_DEPTH = ("FrontCamera", "depth_camera")
#: Stock scene fallback: the chase camera trails the drone and has no depth;
#: DownCamera points at the ground.
CHASE_CAMERA = ("Chase", "scene_camera")
DOWN_CAMERA = ("DownCamera", "scene_camera")
DOWN_DEPTH = ("DownCamera", "depth_camera")
EAGLE_CAMERA = ("Chase", "scene_camera")


#: Yaw control in this physics config disengages the hover controller: a
#: sustained yaw-rate command free-falls the vehicle at ~1.2 m/s, and issuing a
#: concurrent altitude-holding velocity command does not prevent it. Idle holds
#: perfectly (0.00 m/s), so the hover controller works -- it is the yaw path
#: that knocks it out.
#:
#: Short bursts do not. Measured on `robot_quadrotor_fastphysics`:
#:
#:     burst 0.15 s x4 @40 dps   dHeading +95.6 deg   dAlt -0.02 m   OK
#:     burst 0.30 s x4 @40 dps   dHeading +66.1 deg   dAlt -4.00 m   falls
#:     burst 1.00 s x2 @40 dps   dHeading  -5.0 deg   dAlt -2.93 m   falls
#:
#: So yaw is pulsed: rotate briefly, re-issue hover, repeat. Heading
#: accumulates; altitude recovers in between. BURST_S sits below the 0.3 s
#: failure threshold with margin. DEG_PER_BURST is the measured rotation of a
#: single burst, which is larger than rate x duration because of spin-up
#: overhead, so it is calibrated rather than derived.
BURST_S = 0.12
DEG_PER_BURST = 20.0
MAX_BURSTS = 4


def clamp(value: float, lo: float, hi: float) -> float:
    return lo if value < lo else hi if value > hi else value


async def _settle(coro) -> Any:
    """
    Await a ``*_async`` command, including the Task it returns.

    These methods are coroutines that *return a Task*; ``await method()`` yields
    that Task without running it. Every command in this backend goes through
    here or :meth:`ProjectAirSimBackend._run_task`.
    """
    return await (await coro)


class _LoopThread:
    """Run an asyncio loop on a background thread.

    Project AirSim's client is coroutine-driven but ``FlightBackend`` is a
    blocking Protocol that the 50 Hz follow loop calls synchronously. This is the
    seam: coroutines are submitted with ``call_soon_threadsafe`` and drained by
    the worker thread.
    """

    def __init__(self) -> None:
        self.loop = asyncio.new_event_loop()
        self._ready = threading.Event()
        self._thread = threading.Thread(target=self._run, name="pas-loop", daemon=True)
        self._thread.start()
        self._ready.wait(5.0)

    def _run(self) -> None:
        asyncio.set_event_loop(self.loop)
        self.loop.call_soon(self._ready.set)
        self.loop.run_forever()

    def run(self, coro, timeout: float = 60.0) -> Any:
        """Execute a coroutine on the loop thread and wait for its result."""
        fut: asyncio.Future = asyncio.run_coroutine_threadsafe(coro, self.loop)
        return fut.result(timeout=timeout)

    def stop(self) -> None:
        if self.loop.is_running():
            self.loop.call_soon_threadsafe(self.loop.stop)
        self._thread.join(timeout=5.0)


class ProjectAirSimBackend:
    """
    FlightBackend implementation on top of the IAMAI Project AirSim client.

    Mirrors the surface of ``garuda.flight.airsim_client.AirSimClient`` so the
    control loop stays transport-agnostic. Every public method is blocking and
    serialised by one re-entrant lock.
    """

    def __init__(
        self,
        address: str = "127.0.0.1",
        port_topics: int = 8989,
        port_services: int = 8990,
        drone_name: str = DEFAULT_DRONE,
        scene: str = DEFAULT_SCENE,
        chase_cam: tuple[str, str] = FRONT_CAMERA,
        depth_cam: tuple[str, str] = FRONT_DEPTH,
        config_dir: str = "sim_config",
    ) -> None:
        if not PAS_AVAILABLE:
            raise RuntimeError(
                "projectairsim is not installed. pip install projectairsim==1.0.2"
            )
        self.address = address
        self.port_topics = port_topics
        self.port_services = port_services
        self.drone_name = drone_name
        self.scene = scene
        self.config_dir = config_dir
        self._chase = chase_cam
        self._depth_cam = depth_cam

        self._client: Any = None
        self._world: Any = None
        self._drone: Any = None
        self._loop: Optional[_LoopThread] = None
        self._display: Any = None
        self._lock = threading.RLock()

        #: Latest decoded frames, filled by pub/sub callbacks.
        self._frames: dict[str, Any] = {}
        self._frame_count: dict[str, int] = {}

        self.is_connected = False
        self._in_air = False
        self._spawned: list[str] = []
        self._target_alt: Optional[float] = None

    # ── lifecycle ──────────────────────────────────────────────────────
    def connect(self, timeout: float = 90.0) -> bool:
        """Connect, load the scene, spawn the drone, and open the cameras.

        Project AirSim starts with an *empty* scene by design, so the scene and
        the vehicle are created explicitly here.
        """
        with self._lock:
            if self.is_connected:
                return True
            try:
                self._loop = _LoopThread()
                self._client = pas.ProjectAirSimClient(
                    address=self.address,
                    port_topics=self.port_topics,
                    port_services=self.port_services,
                )
                self._client.connect()

                # Scene configs are read from a local ``sim_config/`` folder.
                import os

                cwd = os.getcwd()
                try:
                    os.chdir(cwd)  # keep relative resolution predictable
                except Exception:
                    pass

                self._world = pas.World(
                    self._client, self.scene, delay_after_load_sec=3.0
                )
                self._drone = pas.Drone(self._client, self._world, self.drone_name)
                self._subscribe_cameras()

                # SimpleDrive without Blueprint wiring: enable API control and
                # arm explicitly so raw velocity commands reach the vehicle.
                # These two are plain methods, not coroutines, despite living
                # alongside the *_async commands.
                if not self._drone.enable_api_control():
                    log.warning("enable_api_control returned False")
                if not self._drone.arm():
                    log.warning("arm returned False")

                self.is_connected = True
                atexit.register(self.close)
                log.info(
                    "Project AirSim connected: scene=%s drone=%s (%s:%d/%d)",
                    self.scene, self.drone_name, self.address,
                    self.port_topics, self.port_services,
                )
                return True
            except Exception as e:
                log.error("Project AirSim connect failed: %s: %s", type(e).__name__, e)
                self.is_connected = False
                return False

    def _subscribe_cameras(self) -> None:
        """Open the camera topics.

        ``ImageDisplay.start()`` is mandatory: the stock scene runs a steppable
        clock, and without the display object pumping it the subscriptions are
        accepted but no frames are ever published.
        """
        self._display = ImageDisplay()
        self._display.add_chase_cam("Chase")
        self._display.start()

        sensors = self._drone.sensors
        for label, (cam, key) in (
            ("forward", self._chase),
            ("down", DOWN_CAMERA),
            ("depth", self._depth_cam),
            ("eagle", EAGLE_CAMERA),
        ):
            if cam not in sensors:
                log.warning("sensor %s absent from scene config; %s camera skipped", cam, label)
                continue
            try:
                topic = sensors[cam][key]
            except KeyError:
                log.warning(
                    "%s has no topic %r (available: %s)",
                    cam, key, sorted(sensors[cam].keys()),
                )
                continue
            self._client.subscribe(
                topic, lambda _, v, w=label: self._on_frame(w, v)
            )
            log.info("subscribed %s.%s -> %s", cam, key, label)

    def _on_frame(self, label: str, payload: Any) -> None:
        """Pub/sub callback. Runs on the client's receive thread."""
        try:
            self._frames[label] = unpack_image(payload)
            self._frame_count[label] = self._frame_count.get(label, 0) + 1
        except Exception as e:  # never let a bad frame kill the socket thread
            log.debug("frame decode failed (%s): %s", label, e)

    def close(self) -> None:
        with self._lock:
            try:
                if self._drone is not None and self._in_air and self._loop is not None:
                    self._loop.run(self._drone.land_async(), 30.0)
                for name in self._spawned:
                    try:
                        self._world.destroy_object(name)
                    except Exception:
                        pass
                if self._display is not None:
                    try:
                        self._display.stop()
                    except Exception as e:
                        log.debug("display stop: %s", e)
                # ImageDisplay.start() spawns a NON-daemon render thread. Left
                # alone it keeps the interpreter alive at exit, so a script that
                # errors out appears to hang instead of exiting. Nothing in
                # this backend runs after close(), so joining is safe.
                runner = getattr(self._display, "runner", None)
                if runner is not None and runner.is_alive():
                    runner.daemon = True
                    runner.join(timeout=2.0)
                # This client build has no close()/shutdown(); the NNG sockets
                # are released when the process exits or the loop thread stops.
            except Exception as e:
                log.debug("close error: %s", e)
            finally:
                self.is_connected = False
                self._in_air = False
                self._drone = None
                self._world = None
                self._client = None
                if self._loop is not None:
                    self._loop.stop()
                    self._loop = None
                try:
                    atexit.unregister(self.close)
                except Exception:
                    pass

    def _run(self, coro, timeout: float = 60.0) -> Any:
        """Drain a Project AirSim coroutine to completion (blocking)."""
        if self._loop is None:
            raise RuntimeError("not connected")
        return self._loop.run(coro, timeout=timeout)

    def _run_task(self, coro, timeout: float = 60.0) -> Any:
        """Await a ``*_async`` command, including the Task it returns.

        Project AirSim's async methods are themselves coroutines that *return a
        Task*. ``await method()`` yields that Task without running it, so the
        command is submitted and never completed. The upstream examples all use
        ``await (await drone.method_async(...))`` for this reason.

        Skipping the inner await is silent: the call returns a Task object and
        no exception is raised. The first live run of this backend "succeeded"
        at every call while the drone never moved a centimetre.
        """
        async def _do():
            return await (await coro)

        return self._run(_do(), timeout=timeout)

    # ── FlightBackend surface ──────────────────────────────────────────
    def takeoff(self, altitude_m: float = 4.0, **kw) -> bool:
        """Take off, then climb to ``altitude_m`` AGL.

        ``takeoff_async`` has no altitude argument, so the climb is a separate
        velocity command: NED is +z down, so rising is ``v_down`` negative.
        """
        with self._lock:
            if not self.is_connected:
                return False
            try:
                self._run_task(self._drone.takeoff_async(timeout_sec=30), 60.0)
                current = self.altitude_agl()
                delta = float(altitude_m) - current
                if abs(delta) > 0.3:
                    # NED is +z DOWN, so climbing is a negative v_down. Getting
                    # this sign wrong sinks the drone: the first live run
                    # reported -0.86 m AGL after asking for 6 m.
                    rate = 1.5
                    v_down = -float(np.sign(delta)) * rate
                    self._run_task(
                        self._drone.move_by_velocity_async(
                            v_north=0.0, v_east=0.0, v_down=v_down,
                            duration=min(20.0, abs(delta) / rate),
                        ),
                        40.0,
                    )
                self._run_task(self._drone.hover_async(), 20.0)
                self._in_air = True
                self._target_alt = float(altitude_m)
                log.info("takeoff complete, altitude %.2f m AGL", self.altitude_agl())
                return True
            except Exception as e:
                log.error("takeoff failed: %s: %s", type(e).__name__, e)
                return False

    def is_in_air(self) -> bool:
        return self._in_air

    def hover(self, **kw) -> bool:
        with self._lock:
            if not self.is_connected or self._drone is None:
                return False
            try:
                self._run_task(self._drone.hover_async(), 20.0)
                return True
            except Exception as e:
                log.debug("hover failed: %s", e)
                return False

    def land(self, **kw) -> bool:
        with self._lock:
            if not self.is_connected or self._drone is None:
                return False
            try:
                self._run_task(self._drone.land_async(), 40.0)
                self._in_air = False
                self._target_alt = None
                return True
            except Exception as e:
                log.debug("land failed: %s", e)
                return False

    def heading_deg(self) -> float:
        """Current compass heading from ground truth, degrees."""
        with self._lock:
            try:
                r = self._drone.get_ground_truth_pose()["rotation"]
                num = 2.0 * (r["w"] * r["z"] + r["x"] * r["y"])
                den = 1.0 - 2.0 * (r["y"] * r["y"] + r["z"] * r["z"])
                return math.degrees(math.atan2(num, den)) % 360.0
            except Exception as e:
                log.debug("heading_deg failed: %s", e)
                return float("nan")

    def _yaw_burst(self, rate_dps: float, count: int) -> None:
        """Rotate in short bursts, restoring hover after each one."""
        for _ in range(max(1, min(count, MAX_BURSTS))):
            self._run_task(
                self._drone.rotate_by_yaw_rate_async(
                    yaw_rate=float(rate_dps), duration=BURST_S
                ),
                20.0,
            )
            if self._in_air:
                self._run_task(self._drone.hover_async(), 20.0)

    def rotate_to_heading(self, yaw_deg: float, timeout_s: float = 25.0) -> bool:
        """
        Turn to an absolute heading using pulsed yaw, closed-loop.

        ``rotate_to_yaw_async`` would be the direct call, but it shares the
        free-fall failure described at ``BURST_S`` -- measured, the first command
        after it dropped the drone 6.07 m in 4.1 s. This closes a loop on the
        measured heading instead, pulsing until it is within tolerance.

        Driving yaw by hand is worse: the sign of a positive yaw rate is not
        the sign you would guess, and getting it backwards flew the drone 180
        degrees away from its target on the first attempt.
        """
        target = float(yaw_deg) % 360.0
        t0 = time.monotonic()
        while time.monotonic() - t0 < timeout_s:
            err = (target - self.heading_deg() + 180.0) % 360.0 - 180.0
            if abs(err) < 5.0:
                if self._in_air:
                    self._run_task(self._drone.hover_async(), 20.0)
                return True
            rate = clamp(err * 2.0, -60.0, 60.0)
            bursts = int(round(abs(rate) * 0.20 / DEG_PER_BURST)) or 1
            self._yaw_burst(rate, bursts)
        log.warning("rotate_to_heading(%.0f) timed out at %.0f deg", target,
                    self.heading_deg())
        return False

    def set_target_altitude(self, alt_m: float) -> None:
        """Altitude the movement loop will hold. Set by :meth:`takeoff`."""
        with self._lock:
            self._target_alt = float(alt_m)

    def move_velocity_body(
        self,
        vx: float = 0.0,
        vy: float = 0.0,
        vz: float = 0.0,
        yaw_rate_dps: float = 0.0,
        duration_s: float = 0.2,
        **kw,
    ) -> bool:
        """
        Body-frame velocity plus yaw rate over one control window.

        ``vx``/``vy``/``vz`` map to ``v_forward``/``v_right``/``v_down``.
        ``vz`` is positive-down in NED, matching the AirSim path and the
        controller's ``vz`` sign convention.

        Altitude is held automatically. A bare velocity command in this sim does
        not hold height: three consecutive ticks drifted 6.36 -> 3.23 -> -0.56 m
        and ended on the pavement. So the caller's ``vz`` is treated as a trim
        bias on top of a proportional altitude-hold term, and both are clamped
        to a rate that cannot drive the vehicle into the ground.
        """
        with self._lock:
            if not self.is_connected or not self._in_air:
                return False
            try:
                v_down = float(vz)
                if self._target_alt is not None:
                    err = self._target_alt - self.altitude_agl()  # >0 = below target
                    v_down -= clamp(err * 1.2, -1.5, 1.5)
                v_down = clamp(v_down, -2.0, 2.0)
                dur = float(duration_s)
                vel = self._drone.move_by_velocity_body_frame_async(
                    v_forward=float(vx),
                    v_right=float(vy),
                    v_down=v_down,
                    duration=dur,
                    # yaw MUST stay 0 here; a nonzero yaw rate in this call
                    # disengages the hover controller (see BURST_S).
                    yaw_is_rate=True,
                    yaw=0.0,
                )
                if abs(float(yaw_rate_dps)) >= 6.0:
                    # Translate first, then pulse the yaw. Running them
                    # concurrently does not help: the yaw path drops the vehicle
                    # regardless of what else is being commanded.
                    self._run_task(vel, 20.0)
                    bursts = max(1, int(
                        round(abs(float(yaw_rate_dps)) * dur / DEG_PER_BURST)
                    ))
                    self._yaw_burst(float(yaw_rate_dps), bursts)
                else:
                    self._run_task(vel, 20.0)
                return True
            except Exception as e:
                log.debug("move_velocity_body failed: %s", e)
                return False

    def get_forward_camera(self) -> Optional[np.ndarray]:
        """Forward-facing scene frame as a BGR uint8 array, or None.

        Fail-closed: returns None rather than a blank frame when no image has
        arrived, so the caller reduces authority instead of steering on noise.
        """
        return self._latest("forward", depth=False)

    def get_downward_camera(self) -> Optional[np.ndarray]:
        return self._latest("down", depth=False)

    def get_eagle_camera(self) -> Optional[np.ndarray]:
        """Overhead eagle-eye camera frame as a BGR uint8 array, or None."""
        return self._latest("eagle", depth=False)

    def get_forward_depth(self) -> Optional[np.ndarray]:
        """Metric depth, shaped (h, w) float32 metres, rows in image order.

        ``unpack_image`` returns bottom-up rows for ``16FC1``; this flips once so
        the avoider's row indexing matches the scene frame.
        """
        return self._latest("depth", depth=True)

    def _latest(self, label: str, depth: bool) -> Optional[np.ndarray]:
        with self._lock:
            if not self.is_connected:
                return None
            arr = self._frames.get(label)
            if arr is None:
                return None
            try:
                a = np.asarray(arr)
                if depth:
                    if a.ndim == 3:
                        a = a[:, :, 0]
                    return np.ascontiguousarray(np.flipud(a.astype(np.float32)))
                if a.ndim == 3 and a.shape[2] >= 3:
                    a = a[:, :, :3]
                if a.dtype != np.uint8:
                    a = a.astype(np.float32)
                    scale = 255.0 if a.max() <= 1.5 else 1.0
                    a = (np.clip(a * scale, 0, 255)).astype(np.uint8)
                return np.ascontiguousarray(a)
            except Exception as e:
                log.debug("%s frame conversion failed: %s", label, e)
                return None

    def frames_received(self) -> dict[str, int]:
        """Per-topic frame counts, for diagnostics."""
        return dict(self._frame_count)

    def altitude_agl(self) -> float:
        """Height above the scene origin in metres (NED z is negative up)."""
        with self._lock:
            try:
                t = self._drone.get_ground_truth_pose()["translation"]
                return float(-t["z"])
            except Exception:
                return 0.0

    def get_telemetry(self) -> dict[str, Any]:
        with self._lock:
            if not self.is_connected or self._drone is None:
                return {"connected": False}
            try:
                pose = self._drone.get_ground_truth_pose()
                t = pose["translation"]
                out = {
                    "connected": True,
                    "x": float(t["x"]),
                    "y": float(t["y"]),
                    "z": float(t["z"]),
                    "alt_agl": float(-t["z"]),
                    "in_air": self._in_air,
                }
                # Velocity is optional telemetry. This client build has no
                # get_ground_truth_velocity, so omit the keys rather than
                # fabricate zeros that would read as "stationary".
                try:
                    vel = self._drone.get_ground_truth_velocity()["linear"]
                    out["vx"] = float(vel["x"])
                    out["vy"] = float(vel["y"])
                    out["vz"] = float(vel["z"])
                except AttributeError:
                    pass
                except Exception as e:
                    log.debug("velocity telemetry unavailable: %s", e)
                return out
            except Exception as e:
                log.debug("telemetry failed: %s", e)
                return {"connected": True, "in_air": self._in_air}

    def cycle_view(self, max_switches: int = 4, settle_s: float = 0.8) -> int:
        """
        Cycle the simulator's main window through its streaming cameras.

        ``World.switch_streaming_view()`` advances the *main* view to the next
        camera with ``streaming-enabled``. The stock window is a side/chase
        view, which makes framing impossible to judge, so
        ``scripts/make_follow_config.py`` adds an ``EagleCamera`` above the
        vehicle pitched straight down; this walks the window to it.

        Returns the number of switches the server acknowledged. This API only
        reports success/failure, not a camera name, so we log the acknowledged
        view index and keep the remaining verification explicitly client-side.
        """
        with self._lock:
            if self._world is None:
                return 0
            n = 0
            for index in range(max(0, max_switches)):
                try:
                    acknowledged = self._world.switch_streaming_view()
                    if not acknowledged:
                        log.warning("streaming view switch %d/%d was not acknowledged",
                                    index + 1, max_switches)
                        break
                    n += 1
                    time.sleep(settle_s)
                except (TimeoutError, asyncio.TimeoutError):
                    log.warning("streaming view switch %d/%d timed out; stopping view cycle",
                                index + 1, max_switches)
                    break
                except Exception as e:
                    log.warning("streaming view switch %d/%d failed: %s",
                                index + 1, max_switches, e)
                    break
            log.info("streaming viewport: %d acknowledged switch(es); active camera "
                     "name is not exposed by this client", n)
            return n

    # ── scene inspection ───────────────────────────────────────────────
    def list_scene_objects(self, name_regex: str = ".*") -> list[str]:
        """Actor names in the loaded scene, filtered by a regex.

        ``World.list_actors()`` takes no arguments in this client build, so the
        filter is applied here rather than server-side.
        """
        import re

        with self._lock:
            if self._world is None:
                return []
            try:
                names = list(self._world.list_actors())
            except Exception as e:
                log.debug("list_actors failed: %s", e)
                return []
            if name_regex in (".*", ""):
                return names
            try:
                rx = re.compile(name_regex, re.IGNORECASE)
            except re.error:
                return names
            return [n for n in names if rx.search(n)]

    @staticmethod
    def _make_pose(xyz: tuple[float, float, float], yaw_deg: float = 0.0) -> Any:
        """
        Build a ``Pose``/``Transform`` dict.

        The key is ``translation``, not ``position``, and there is **no**
        ``scale`` inside the pose -- scale is a separate argument to the spawn
        calls. Using ``position`` makes ``Vector3(None)`` raise
        ``TypeError: 'NoneType' object is not subscriptable`` deep inside the
        client, which reads like a server rejection.
        """
        from projectairsim.types import Pose

        half = math.radians(yaw_deg) * 0.5
        return Pose(
            {
                "frame_id": "DEFAULT_ID",
                "translation": {"x": float(xyz[0]), "y": float(xyz[1]), "z": float(xyz[2])},
                "rotation": {"w": math.cos(half), "x": 0.0, "y": 0.0, "z": math.sin(half)},
            }
        )

    def spawn_glb(
        self,
        name: str,
        blob: bytes,
        xyz: tuple[float, float, float],
        scale: tuple[float, float, float] = (1.0, 1.0, 1.0),
        file_format: str = "gltf",
        is_binary: bool = True,
        enable_physics: bool = False,
    ) -> Optional[str]:
        """
        Spawn an actor from raw glTF bytes.

        This is the only way to put a *new* kind of object in the scene.
        ``spawn_object`` serves packaged engine assets and returns None for
        anything else, while ``spawn_object_from_file`` ships the bytes straight
        to the server, so the asset does not need to exist on the machine. The
        server accepts ``file_format="gltf"`` only.

        See ``garuda.flight.humanoid_glb`` for a dependency-free human mesh,
        built because this box has an ``AnimatedCharacter.fbx`` and a
        ``Mikkt_SkeletalMesh.fbx`` in the UE 5.7.4 content but no FBX->glTF
        converter.
        """
        with self._lock:
            if self._world is None:
                return None
            try:
                got = self._world.spawn_object_from_file(
                    name,
                    file_format,
                    blob,
                    is_binary,
                    self._make_pose(xyz),
                    [float(s) for s in scale],
                    enable_physics,
                )
                if got:
                    self._spawned.append(got)
                    log.info("spawned %s (%d bytes) -> %s", name, len(blob), got)
                else:
                    log.warning("spawn_object_from_file(%s) returned None", name)
                return got
            except Exception as e:
                log.error("spawn_glb(%s) failed: %s: %s", name, type(e).__name__, e)
                return None

    def move_actor_along(
        self,
        actor_name: str,
        waypoints: Sequence[tuple[float, ...]],
        speed_mps: float = 1.0,
        z: float = 0.0,
        repeat_duration_s: float = 300.0,
    ) -> bool:
        """
        Drive a spawned actor along a closed NED path continuously.

        Project AirSim has no per-actor velocity command, but
        ``import_ned_trajectory`` moves a named actor over time. Walking the
        subject is what makes a follow demo meaningful: a stationary target
        proves the framing law but never exercises the approach loop or the
        depth veto.

        Waypoints may be ``(x, y)`` or ``(x, y, z)``; a 2-tuple takes the
        ``z`` argument. Calculates real Euclidean segment distances, subdivides
        into ~1m steps for smooth movement, and repeats the path until
        ``repeat_duration_s`` is reached.

        Returns False if the trajectory is rejected, e.g. a name collision.
        """
        with self._lock:
            if self._world is None or len(waypoints) < 2:
                return False
            try:
                pts = [tuple(w) + (z,) if len(w) == 2 else tuple(w) for w in waypoints]
                if pts[-1] != pts[0]:
                    pts.append(pts[0])

                times = [0.0]
                xs = [float(pts[0][0])]
                ys = [float(pts[0][1])]
                zs = [float(pts[0][2])]

                t_cur = 0.0
                while t_cur < repeat_duration_s:
                    for i in range(len(pts) - 1):
                        p1 = pts[i]
                        p2 = pts[i + 1]
                        dist = math.hypot(p2[0] - p1[0], p2[1] - p1[1], p2[2] - p1[2])
                        if dist < 1e-4:
                            continue
                        n_sub = max(1, int(math.ceil(dist / 1.0)))
                        dt = (dist / n_sub) / max(speed_mps, 0.1)
                        for k in range(1, n_sub + 1):
                            alpha = k / n_sub
                            px = p1[0] + alpha * (p2[0] - p1[0])
                            py = p1[1] + alpha * (p2[1] - p1[1])
                            pz = p1[2] + alpha * (p2[2] - p1[2])
                            t_cur += dt
                            times.append(float(t_cur))
                            xs.append(float(px))
                            ys.append(float(py))
                            zs.append(float(pz))

                from garuda.flight.actor_stepper import ActorStepper
                if not hasattr(self, "_actor_steppers"):
                    self._actor_steppers = {}
                self._actor_steppers[actor_name] = ActorStepper(
                    self._world, actor_name, waypoints, speed_mps=speed_mps, z=z
                )
                log.info(
                    "Initialized actor %s route with %d waypoints",
                    actor_name, len(waypoints),
                )
                return True
            except Exception as e:
                log.error("move_actor_along(%s) failed: %s: %s", actor_name, type(e).__name__, e)
                return False

    def step_actor(
        self,
        actor_name: str,
        waypoints: Sequence[tuple[float, ...]],
        speed_mps: float = 1.0,
        dt: float = 0.15,
        z: float = 0.0,
    ) -> Optional[tuple[float, float, float]]:
        """Advance a spawned actor one time step along waypoints using ActorStepper."""
        with self._lock:
            if self._world is None or len(waypoints) < 2:
                return None
            try:
                from garuda.flight.actor_stepper import ActorStepper
                if not hasattr(self, "_actor_steppers"):
                    self._actor_steppers = {}
                if actor_name not in self._actor_steppers:
                    self._actor_steppers[actor_name] = ActorStepper(
                        self._world, actor_name, waypoints, speed_mps=speed_mps, z=z
                    )
                return self._actor_steppers[actor_name].step(dt=dt)
            except Exception as e:
                log.error("step_actor(%s) failed: %s: %s", actor_name, type(e).__name__, e)
                return None

    def actor_position(self, actor_name: str) -> Optional[tuple[float, float, float]]:
        """
        Ground-truth position of a spawned actor, in NED metres.

        Used for diagnostics only. The control loop must consume camera frames,
        never actor poses -- steering from ground truth invalidates the demo.
        """
        with self._lock:
            if self._world is None:
                return None
            try:
                t = self._world.get_object_pose(actor_name)["translation"]
                return (float(t["x"]), float(t["y"]), float(t["z"]))
            except Exception as e:
                log.debug("actor_position(%s) failed: %s", actor_name, e)
                return None

    def spawn_object(
        self,
        name: str,
        asset_path: str,
        xyz: tuple[float, float, float],
        scale: tuple[float, float, float] = (1.0, 1.0, 1.0),
    ) -> Optional[str]:
        """
        Spawn a scene actor from a packaged engine asset.

        This is the call that crashes the UE 4.27 CityEnviron build. The IAMAI
        fork supports it, but a packaged environment only ships the assets it
        was built with, so an unpackaged path (e.g.
        ``/Engine/BasicShapes/Cube``) returns None rather than raising. Use
        :meth:`spawn_glb` for anything that is not already in the environment.
        """
        with self._lock:
            if self._world is None:
                return None
            try:
                got = self._world.spawn_object(
                    name,
                    asset_path,
                    self._make_pose(xyz),
                    [float(s) for s in scale],
                    False,
                )
                if got:
                    self._spawned.append(got)
                    log.info("spawned %s -> %s", asset_path, got)
                else:
                    log.warning(
                        "spawn_object(%s) returned None - the packaged environment "
                        "only contains assets it was built with",
                        asset_path,
                    )
                return got
            except Exception as e:
                log.error("spawn_object(%s) failed: %s: %s", name, type(e).__name__, e)
                return None
